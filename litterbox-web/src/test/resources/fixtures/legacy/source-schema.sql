CREATE TABLE feedback (
    id INT NOT NULL AUTO_INCREMENT,
    program INT NOT NULL,
    pattern VARCHAR(120) NOT NULL,
    reaction TINYINT NOT NULL,
    time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_feedback_program_pattern (program, pattern),
    CONSTRAINT fk_feedback_program FOREIGN KEY (program) REFERENCES programme (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE fragen (
    id INT NOT NULL AUTO_INCREMENT,
    programName VARCHAR(100) NOT NULL,
    question VARCHAR(500) NOT NULL,
    answer VARCHAR(500) NOT NULL,
    correct TEXT NULL,
    time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE `extId` (
    id INT NOT NULL AUTO_INCREMENT,
    extId VARCHAR(8) NOT NULL,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
